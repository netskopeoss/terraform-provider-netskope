// This file adds a ModifyPlan method to NPARulesResource to normalize
// list attribute ordering and prevent perpetual plan drift.
//
// Problem: Terraform's ListAttribute compares plan vs state by position.
// The API may return list elements in a different order than the user's HCL
// config, causing every plan to show spurious "update in-place" diffs even
// though the set of elements is identical.
//
// Fix: Before Terraform compares plan to state, check if each list attribute
// contains the same set of elements in a different order. If so, use the
// state values in the state order.
//
// This file is NOT generated by Speakeasy and will not be overwritten.
// See docs/bugs/BUG-002-config-order-plan-drift.md for details.

package provider

import (
	"context"
	"encoding/json"
	"sort"
	"strings"

	"github.com/hashicorp/terraform-plugin-framework/diag"
	"github.com/hashicorp/terraform-plugin-framework/path"
	"github.com/hashicorp/terraform-plugin-framework/resource"
	"github.com/hashicorp/terraform-plugin-framework/types"
)

// npaTemplatePrivateKey is the private state key storing the last template display
// name sent to the API. Private state survives across provider processes (TFC,
// terraform-plugin-testing) — unlike in-process memory caches.
// See docs/bugs/BUG-021-npa-template-private-state.md.
const npaTemplatePrivateKey = "npa_template_display"

// templateStore abstracts private-state GetKey/SetKey for template display names.
// *privatestate.ProviderData (internal framework package, not importable by external
// modules) satisfies this interface implicitly. Tests inject a map-backed fake.
type templateStore interface {
	GetKey(ctx context.Context, key string) ([]byte, diag.Diagnostics)
	SetKey(ctx context.Context, key string, value []byte) diag.Diagnostics
}

// templatePlanDecision is the pure decision core for suppressTemplateDrift.
// Given cfg (config template), st (state template), last (last value written to
// private state), and otherChanges (whether other attributes differ between plan
// and state after normalizations), it returns the value to use for plan.template
// and whether this is a "new record" case (branch 3: first-time seen or changed).
//
// Empty-string sentinel is used for null/unknown inputs.
//
// Branches (see docs/bugs/BUG-021-npa-template-private-state.md §Fix):
//
//	Branch 1 (nothing to reconcile): cfg is a filename, st is not a filename,
//	  values are equal, or either is empty → use cfg, record=false.
//	Branch 2 (suppress): st is a filename for the same display name we last sent
//	  → use st to suppress spurious diff, record=false.
//	  If other attributes also changed, a PUT happens anyway: use cfg so the API
//	  accepts the display name (filename rejected on some tenants).
//	Branch 3 (honest diff): private state absent or display name changed
//	  → use cfg (honest diff), record=true (persist for next plan).
func templatePlanDecision(cfg, st, last string, otherChanges bool) (planValue string, record bool) {
	// Branch 1: nothing to reconcile.
	if st == "" || cfg == "" || cfg == st ||
		strings.HasSuffix(cfg, ".html") ||
		!strings.HasSuffix(st, ".html") {
		return cfg, false
	}
	// cfg is a display name, st is a .html filename.
	if last != "" && last == cfg {
		// Branch 2: we know this display name maps to the current filename.
		if otherChanges {
			// PUT is happening anyway — send the display name so the API accepts it.
			return cfg, false
		}
		return st, false // suppress: plan = state, no new record needed
	}
	// Branch 3: first time, import, upgrade from ≤0.4.12, or template changed.
	return cfg, true
}

// Compile-time check that NPARulesResource implements ModifyPlan.
var _ resource.ResourceWithModifyPlan = &NPARulesResource{}

func (r *NPARulesResource) ModifyPlan(ctx context.Context, req resource.ModifyPlanRequest, resp *resource.ModifyPlanResponse) {
	// Build nil-safe private-state stores. Assigning a nil *ProviderData directly to
	// a templateStore interface yields a non-nil interface (non-nil type, nil pointer),
	// which would cause SetKey to return an error diagnostic on some framework versions.
	// Guarding the concrete pointer before assignment avoids this.
	var readStore, writeStore templateStore
	if req.Private != nil {
		readStore = req.Private
	}
	if resp.Private != nil {
		writeStore = resp.Private
	}

	// Skip on create (no prior state) or destroy (null plan).
	// suppressTemplateDrift is still called here so it records config.template in
	// private state (step 1) even for create plans. The key is not forwarded to
	// CreateResponse.Private by the framework today (§4.3), so it is first effectively
	// persisted by the first update — but writing here is harmless and future-proofs
	// Create calls that do forward resp.Private.
	if req.State.Raw.IsNull() || req.Plan.Raw.IsNull() {
		suppressTemplateDrift(ctx, req, resp, readStore, writeStore)
		return
	}

	// Preserve computed-only attributes that don't change after creation.
	// Without this, Terraform shows (known after apply) on every plan.
	// group_name: GET-by-ID never returns it, so state is always null.
	// Without preservation it stays (known after apply) and keeps updates alive.
	// See docs/bugs/BUG-019-block-rule-template-phantom-update.md
	preserveComputedStringAttr(ctx, req, resp, path.Root("id"))
	preserveComputedStringAttr(ctx, req, resp, path.Root("group_name"))

	// All Computed+Optional list attributes under rule_data.
	normalizeStringListAttr(ctx, req, resp, path.Root("rule_data").AtName("private_apps"))
	normalizeStringListAttr(ctx, req, resp, path.Root("rule_data").AtName("users"))
	normalizeStringListAttr(ctx, req, resp, path.Root("rule_data").AtName("user_groups"))
	normalizeStringListAttr(ctx, req, resp, path.Root("rule_data").AtName("access_method"))
	normalizeStringListAttr(ctx, req, resp, path.Root("rule_data").AtName("src_countries"))
	normalizeStringListAttr(ctx, req, resp, path.Root("rule_data").AtName("organization_units"))
	normalizeStringListAttr(ctx, req, resp, path.Root("rule_data").AtName("net_location_obj"))
	// private_app_tag_ids: when set via private_app_tags (name resolution), the API
	// does not return privateAppTagIds on GET. Preserve state when not in config so
	// the resolved IDs don't vanish on refresh. normalizeStringListAttr handles
	// ordering when the user sets the field explicitly.
	preserveComputedListAttr(ctx, req, resp, path.Root("rule_data").AtName("private_app_tag_ids"))
	normalizeStringListAttr(ctx, req, resp, path.Root("rule_data").AtName("private_app_tag_ids"))
	normalizeStringListAttr(ctx, req, resp, path.Root("rule_data").AtName("device_classification_id"))
	normalizeStringListAttr(ctx, req, resp, path.Root("rule_data").AtName("classification"))
	normalizeStringListAttr(ctx, req, resp, path.Root("rule_data").AtName("os"))

	// schedule is a ListNestedAttribute — x-speakeasy-param-suppress-computed-diff
	// does not generate a list plan modifier for nested-object lists. Preserve state
	// manually so it does not show (known after apply) when not set in config.
	preserveComputedListAttr(ctx, req, resp, path.Root("rule_data").AtName("schedule"))

	// private_app_tags is auto-populated by the API as a side-effect of setting
	// private_app_tag_ids (name enrichment). Users don't set it directly. Preserve
	// state when not in config to prevent phantom removal diffs.
	preserveComputedListAttr(ctx, req, resp, path.Root("rule_data").AtName("private_app_tags"))

	// These SingleNestedAttributes use SuppressDiff(ExplicitSuppress) which only
	// suppresses when the value was previously non-null. For rules that never set
	// these fields (state is null), we must explicitly use state to prevent
	// (known after apply) on every plan.
	preserveComputedObjectAttr(ctx, req, resp, path.Root("rule_data").AtName("periodic_reauth"))
	preserveComputedObjectAttr(ctx, req, resp, path.Root("rule_data").AtName("user_confidence"))

	// Suppress template display-name/file-name drift.
	// MUST be called last so Raw.Equal inside suppressTemplateDrift reflects a
	// fully-normalized plan (all other attributes already settled).
	// See: https://github.com/netskopeoss/terraform-provider-netskope/issues/79
	suppressTemplateDrift(ctx, req, resp, readStore, writeStore)
}

// suppressTemplateDrift reconciles the template display name (in config) with the
// .html filename the API returns on GET. Private state is used to remember the last
// display name sent so the plan modifier can suppress spurious diffs across provider
// processes (TFC, terraform-plugin-testing).
//
// Step 1 (write private state) always runs first — even for create/destroy plans —
// so the key is available on the very next update plan.
//
// Step 2 (reconcile display-name↔filename) only runs for update plans (both state
// and plan non-null).
//
// Known limitation: an out-of-band UI template change (5.html → 7.html) is not detected
// while the configured display name is unchanged (branch 2 will suppress it).
// See docs/bugs/BUG-021-npa-template-private-state.md
// See: https://github.com/netskopeoss/terraform-provider-netskope/issues/129
// See: https://github.com/netskopeoss/terraform-provider-netskope/issues/124
// See: https://github.com/netskopeoss/terraform-provider-netskope/issues/118
func suppressTemplateDrift(ctx context.Context, req resource.ModifyPlanRequest, resp *resource.ModifyPlanResponse, readStore, writeStore templateStore) {
	templatePath := path.Root("rule_data").AtName("match_criteria_action").AtName("template")

	// Step 1: read the last display name sent to the API from private state.
	//
	// IMPORTANT: this read MUST come before the private-state write in Step 2.
	// In terraform-plugin-framework ≥1.2, req.Private and resp.Private share the
	// same underlying ProviderData object — a SetKey on resp.Private is immediately
	// visible to a subsequent GetKey on req.Private within the same ModifyPlan call.
	// Reading lastSent first preserves the value from the previous apply; reading
	// after writing would return the just-written config value, causing Branch 2
	// to suppress a genuine template change (RC-4 / issue #129 regression).
	lastSent := ""
	if readStore != nil {
		raw, d := readStore.GetKey(ctx, npaTemplatePrivateKey)
		resp.Diagnostics.Append(d...)
		if resp.Diagnostics.HasError() {
			return
		}
		if len(raw) > 0 {
			var decoded string
			if err := json.Unmarshal(raw, &decoded); err == nil {
				lastSent = decoded
			}
		}
	}

	// Step 2: record config.template in private state so the next plan can suppress
	// the display-name↔filename diff without an API round-trip.
	// Value must be valid JSON — json.Marshal encodes the string with quotes.
	if writeStore != nil && !req.Plan.Raw.IsNull() {
		var cfgTpl types.String
		resp.Diagnostics.Append(req.Config.GetAttribute(ctx, templatePath, &cfgTpl)...)
		if !resp.Diagnostics.HasError() && !cfgTpl.IsNull() && !cfgTpl.IsUnknown() && cfgTpl.ValueString() != "" {
			encoded, marshalErr := json.Marshal(cfgTpl.ValueString())
			if marshalErr == nil {
				resp.Diagnostics.Append(writeStore.SetKey(ctx, npaTemplatePrivateKey, encoded)...)
			}
		}
	}

	// Step 3: only reconcile on update plans (both state and plan present).
	if req.State.Raw.IsNull() || req.Plan.Raw.IsNull() {
		return
	}

	var configVal, stateVal types.String
	resp.Diagnostics.Append(req.Config.GetAttribute(ctx, templatePath, &configVal)...)
	resp.Diagnostics.Append(req.State.GetAttribute(ctx, templatePath, &stateVal)...)
	if resp.Diagnostics.HasError() {
		return
	}

	// Normalize null/unknown to empty string for the pure decision function.
	cfg, st := "", ""
	if !configVal.IsNull() && !configVal.IsUnknown() {
		cfg = configVal.ValueString()
	}
	if !stateVal.IsNull() && !stateVal.IsUnknown() {
		st = stateVal.ValueString()
	}

	// Branch 1 guard: return early when there is nothing to reconcile.
	// This MUST come before the tentative plan.template = stateVal mutation below
	// to prevent corrupting the plan when configVal is null (config omits template).
	// For a Computed+Optional field, null config means "preserve state" — the
	// framework's ExplicitSuppress plan modifier already keeps plan = state, so we
	// must not overwrite it with configVal (null) when restoring after a non-suppress
	// decision. Mirrors the Branch 1 conditions in templatePlanDecision exactly.
	if cfg == "" || st == "" || cfg == st ||
		strings.HasSuffix(cfg, ".html") ||
		!strings.HasSuffix(st, ".html") {
		return
	}

	// Tentatively suppress (set plan.template = state.template) so that the
	// Raw.Equal check below reflects only OTHER attribute differences, not the
	// display-name↔filename diff itself. This mirrors the original logic.
	resp.Diagnostics.Append(resp.Plan.SetAttribute(ctx, templatePath, stateVal)...)
	if resp.Diagnostics.HasError() {
		return
	}
	// otherChanges is true when other attributes differ even after template suppression.
	otherChanges := !resp.Plan.Raw.Equal(req.State.Raw)

	planValue, _ := templatePlanDecision(cfg, st, lastSent, otherChanges)

	// If the decision didn't suppress (planValue = cfg rather than st), undo
	// the tentative suppression and restore the display name.
	if planValue != st {
		resp.Diagnostics.Append(resp.Plan.SetAttribute(ctx, templatePath, configVal)...)
	}
}

// preserveComputedObjectAttr copies the state value to the plan for a
// computed SingleNestedAttribute when the attribute is not set in the config.
//
// Handles two cases:
//   - plan unknown (first create, before API returns a value): prevents (known after apply)
//   - plan null (attribute omitted from config, state is non-null): prevents phantom
//     removal diffs on post-import plans and on updates that don't touch the field
//
// For user_confidence, Speakeasy generates SuppressDiff(ExplicitSuppress)
// which covers the non-null state case. periodic_reauth uses a $ref so that
// plan modifier is not generated — this function covers both cases for both fields.
//
// This matches ExplicitSuppress semantics: the field is preserved when not in
// config. Users cannot clear the field by omitting it (same API/omitempty limitation
// as schedule and private_app_tags).
func preserveComputedObjectAttr(ctx context.Context, req resource.ModifyPlanRequest, resp *resource.ModifyPlanResponse, attrPath path.Path) {
	var stateVal, planVal types.Object

	resp.Diagnostics.Append(req.State.GetAttribute(ctx, attrPath, &stateVal)...)
	resp.Diagnostics.Append(req.Plan.GetAttribute(ctx, attrPath, &planVal)...)
	if resp.Diagnostics.HasError() {
		return
	}

	// If state is unknown there is nothing meaningful to preserve.
	if stateVal.IsUnknown() {
		return
	}

	// Preserve state when plan is unknown (not yet computed) or null (omitted
	// from config). An explicit config value passes through unchanged.
	if planVal.IsUnknown() || planVal.IsNull() {
		resp.Diagnostics.Append(resp.Plan.SetAttribute(ctx, attrPath, stateVal)...)
	}
}

// preserveComputedListAttr copies the state value to the plan for a
// computed list attribute when the attribute is not set in the config.
// Handles both:
//   - unknown plan (Computed+Optional, first create): prevents (known after apply)
//   - null plan (Computed+Optional, no Default, attribute absent from config):
//     prevents phantom removal diffs on API-computed side-effects
//   - empty plan from Default (Computed+Optional with Default: [], attribute absent
//     from config): prevents phantom removal diffs when a Default turns null → []
//
// The config value is the canonical signal for "user didn't set this". If config is
// null, the attribute was omitted from HCL and we preserve state even if the
// Default produced [] in the plan. An explicit config value (including []) passes
// through so users can intentionally set or clear the list.
//
// Used for ListNestedAttribute (schedule) where x-speakeasy-param-suppress-computed-diff
// generates no plan modifier, and for API side-effect lists (private_app_tags)
// that are auto-populated from sibling fields.
func preserveComputedListAttr(ctx context.Context, req resource.ModifyPlanRequest, resp *resource.ModifyPlanResponse, attrPath path.Path) {
	var stateVal, planVal, configVal types.List

	resp.Diagnostics.Append(req.State.GetAttribute(ctx, attrPath, &stateVal)...)
	resp.Diagnostics.Append(req.Plan.GetAttribute(ctx, attrPath, &planVal)...)
	resp.Diagnostics.Append(req.Config.GetAttribute(ctx, attrPath, &configVal)...)
	if resp.Diagnostics.HasError() {
		return
	}

	// If state is unknown there is nothing meaningful to preserve.
	if stateVal.IsUnknown() {
		return
	}

	// Preserve state when plan is unknown (first create, not yet computed) or
	// when the attribute was not set in config (configVal is null).
	// Checking config rather than plan handles the case where a Default value
	// turns null → [] in the plan, which would otherwise bypass the IsNull check.
	if planVal.IsUnknown() || configVal.IsNull() {
		resp.Diagnostics.Append(resp.Plan.SetAttribute(ctx, attrPath, stateVal)...)
	}
}

// preserveComputedStringAttr copies the state value to the plan for a
// computed-only attribute. Without this, computed attributes show
// (known after apply) on every plan that touches the resource.
// Handles both cases:
//   - state has a real value (e.g. id): plan gets the known value
//   - state is null (e.g. group_name, never returned by GET-by-ID): plan
//     stays null, which collapses to a no-op vs null state
func preserveComputedStringAttr(ctx context.Context, req resource.ModifyPlanRequest, resp *resource.ModifyPlanResponse, attrPath path.Path) {
	var stateVal, planVal types.String

	resp.Diagnostics.Append(req.State.GetAttribute(ctx, attrPath, &stateVal)...)
	resp.Diagnostics.Append(req.Plan.GetAttribute(ctx, attrPath, &planVal)...)
	if resp.Diagnostics.HasError() {
		return
	}

	// If state is known (or null) and plan is unknown, use state value.
	// This is equivalent to UseStateForUnknown for computed-only fields.
	if planVal.IsUnknown() && !stateVal.IsUnknown() {
		resp.Diagnostics.Append(resp.Plan.SetAttribute(ctx, attrPath, stateVal)...)
	}
}

// normalizeStringListAttr checks if plan and state have the same set of string
// values for the given attribute path. If yes, uses the state list to prevent
// false drift from ordering differences.
func normalizeStringListAttr(ctx context.Context, req resource.ModifyPlanRequest, resp *resource.ModifyPlanResponse, attrPath path.Path) {
	var planList, stateList types.List

	resp.Diagnostics.Append(req.Plan.GetAttribute(ctx, attrPath, &planList)...)
	resp.Diagnostics.Append(req.State.GetAttribute(ctx, attrPath, &stateList)...)
	if resp.Diagnostics.HasError() {
		return
	}

	// If either is null or unknown, skip normalization.
	if planList.IsNull() || planList.IsUnknown() || stateList.IsNull() || stateList.IsUnknown() {
		return
	}

	planElems := planList.Elements()
	stateElems := stateList.Elements()

	// Different count means elements were added or removed — a real change.
	if len(planElems) != len(stateElems) {
		return
	}

	// Extract string values and sort to compare as sets.
	planVals := make([]string, 0, len(planElems))
	for _, e := range planElems {
		sv, ok := e.(types.String)
		if !ok || sv.IsUnknown() || sv.IsNull() {
			return
		}
		planVals = append(planVals, sv.ValueString())
	}

	stateVals := make([]string, 0, len(stateElems))
	for _, e := range stateElems {
		sv, ok := e.(types.String)
		if !ok || sv.IsUnknown() || sv.IsNull() {
			return
		}
		stateVals = append(stateVals, sv.ValueString())
	}

	sort.Strings(planVals)
	sort.Strings(stateVals)

	for i := range planVals {
		if planVals[i] != stateVals[i] {
			return // Different elements — real change.
		}
	}

	// Same set of values, different order. Use state to suppress false drift.
	resp.Diagnostics.Append(resp.Plan.SetAttribute(ctx, attrPath, stateList)...)
}
