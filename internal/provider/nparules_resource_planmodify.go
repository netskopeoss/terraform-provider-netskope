// This file adds a ModifyPlan method to NPARulesResource to normalize
// list attribute ordering and prevent perpetual plan drift.
//
// Problem: Terraform's ListAttribute compares plan vs state by position.
// The API may return list elements in a different order than the user's HCL
// config, causing every plan to show spurious "update in-place" diffs even
// though the set of elements is identical.
//
// Fix: Before Terraform compares plan to state, check if each list attribute
// contains the same set of elements in a different order. If so, use the
// state values in the state order.
//
// This file is NOT generated by Speakeasy and will not be overwritten.
// See docs/bugs/BUG-002-config-order-plan-drift.md for details.

package provider

import (
	"context"
	"sort"

	"github.com/hashicorp/terraform-plugin-framework/path"
	"github.com/hashicorp/terraform-plugin-framework/resource"
	"github.com/hashicorp/terraform-plugin-framework/types"
)

// Compile-time check that NPARulesResource implements ModifyPlan.
var _ resource.ResourceWithModifyPlan = &NPARulesResource{}

func (r *NPARulesResource) ModifyPlan(ctx context.Context, req resource.ModifyPlanRequest, resp *resource.ModifyPlanResponse) {
	// Skip on create (no prior state) or destroy (null plan).
	if req.State.Raw.IsNull() || req.Plan.Raw.IsNull() {
		return
	}

	// All Computed+Optional list attributes under rule_data.
	normalizeStringListAttr(ctx, req, resp, path.Root("rule_data").AtName("private_apps"))
	normalizeStringListAttr(ctx, req, resp, path.Root("rule_data").AtName("users"))
	normalizeStringListAttr(ctx, req, resp, path.Root("rule_data").AtName("user_groups"))
	normalizeStringListAttr(ctx, req, resp, path.Root("rule_data").AtName("access_method"))
	normalizeStringListAttr(ctx, req, resp, path.Root("rule_data").AtName("src_countries"))
	normalizeStringListAttr(ctx, req, resp, path.Root("rule_data").AtName("organization_units"))
	normalizeStringListAttr(ctx, req, resp, path.Root("rule_data").AtName("net_location_obj"))
	normalizeStringListAttr(ctx, req, resp, path.Root("rule_data").AtName("private_app_tags"))
	normalizeStringListAttr(ctx, req, resp, path.Root("rule_data").AtName("device_classification_id"))
}

// normalizeStringListAttr checks if plan and state have the same set of string
// values for the given attribute path. If yes, uses the state list to prevent
// false drift from ordering differences.
func normalizeStringListAttr(ctx context.Context, req resource.ModifyPlanRequest, resp *resource.ModifyPlanResponse, attrPath path.Path) {
	var planList, stateList types.List

	resp.Diagnostics.Append(req.Plan.GetAttribute(ctx, attrPath, &planList)...)
	resp.Diagnostics.Append(req.State.GetAttribute(ctx, attrPath, &stateList)...)
	if resp.Diagnostics.HasError() {
		return
	}

	// If either is null or unknown, skip normalization.
	if planList.IsNull() || planList.IsUnknown() || stateList.IsNull() || stateList.IsUnknown() {
		return
	}

	planElems := planList.Elements()
	stateElems := stateList.Elements()

	// Different count means elements were added or removed — a real change.
	if len(planElems) != len(stateElems) {
		return
	}

	// Extract string values and sort to compare as sets.
	planVals := make([]string, 0, len(planElems))
	for _, e := range planElems {
		sv, ok := e.(types.String)
		if !ok || sv.IsUnknown() || sv.IsNull() {
			return
		}
		planVals = append(planVals, sv.ValueString())
	}

	stateVals := make([]string, 0, len(stateElems))
	for _, e := range stateElems {
		sv, ok := e.(types.String)
		if !ok || sv.IsUnknown() || sv.IsNull() {
			return
		}
		stateVals = append(stateVals, sv.ValueString())
	}

	sort.Strings(planVals)
	sort.Strings(stateVals)

	for i := range planVals {
		if planVals[i] != stateVals[i] {
			return // Different elements — real change.
		}
	}

	// Same set of values, different order. Use state to suppress false drift.
	resp.Diagnostics.Append(resp.Plan.SetAttribute(ctx, attrPath, stateList)...)
}

