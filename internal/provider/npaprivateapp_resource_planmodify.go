// This file adds a ModifyPlan method to NPAPrivateAppResource to normalize
// list attribute ordering and prevent perpetual plan drift.
//
// Problem 1 (BUG-002): The AfterSuccess hooks sort protocols, publishers, and
// tags in the API response before writing to state. But Terraform's
// ListNestedAttribute compares plan vs state by position. If the user's HCL
// config order differs from the hook's sorted order, every plan shows spurious
// "update in-place".
//
// Problem 2: The generated schema lacks UseStateForUnknown plan modifiers on
// Computed(+Optional) attributes. When these attributes are not in the user's
// config, Terraform marks them as unknown, which cascades to mark ALL Computed
// attributes as unknown — causing false drift on fields like private_app_id.
//
// Fix: Before Terraform compares plan to state:
// - Preserve state values for Computed attributes that are unknown in plan
// - Normalize list ordering when plan and state have the same elements
//
// This file is NOT generated by Speakeasy and will not be overwritten.
// See docs/bugs/BUG-002-config-order-plan-drift.md for details.

