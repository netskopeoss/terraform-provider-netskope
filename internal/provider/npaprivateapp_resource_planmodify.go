// Compile-time check that NPAPrivateAppResource implements ModifyPlan.
var _ resource.ResourceWithModifyPlan = &NPAPrivateAppResource{}

func (r *NPAPrivateAppResource) ModifyPlan(ctx context.Context, req resource.ModifyPlanRequest, resp *resource.ModifyPlanResponse) {
	// Skip on create (no prior state) or destroy (null plan).
	if req.State.Raw.IsNull() || req.Plan.Raw.IsNull() {
		return
	}

	// Preserve Computed attributes that are unknown in plan but known in state.
	// The generated schema lacks UseStateForUnknown plan modifiers, so without
	// this, any Computed(+Optional) attribute not in config shows as "known
	// after apply" and cascades to make ALL Computed attributes unknown.
	preserveStateForUnknownInt32(ctx, req, resp, path.Root("private_app_id"))
	preserveStateForUnknownString(ctx, req, resp, path.Root("real_host"))

	// Normalize list ordering to prevent false drift from position differences.
	normalizeProtocolsOrder(ctx, req, resp)
	normalizePublishersOrder(ctx, req, resp)
	normalizeTagsOrder(ctx, req, resp)
}

// preserveStateForUnknownString copies a string attribute from state to plan
// when the plan value is unknown. This is the ModifyPlan equivalent of
// UseStateForUnknown for attributes where we can't modify the generated schema.
func preserveStateForUnknownString(ctx context.Context, req resource.ModifyPlanRequest, resp *resource.ModifyPlanResponse, attrPath path.Path) {
	var planVal, stateVal types.String
	resp.Diagnostics.Append(req.Plan.GetAttribute(ctx, attrPath, &planVal)...)
	resp.Diagnostics.Append(req.State.GetAttribute(ctx, attrPath, &stateVal)...)
	if resp.Diagnostics.HasError() {
		return
	}

	if planVal.IsUnknown() && !stateVal.IsUnknown() {
		resp.Diagnostics.Append(resp.Plan.SetAttribute(ctx, attrPath, stateVal)...)
	}
}

