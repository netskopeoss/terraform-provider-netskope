// normalizeProtocolsOrder checks if plan and state have the same set of
// protocols (matched by protocol+port). If yes, uses the state list as the
// plan to prevent false drift from ordering differences.
// If the plan is unknown (attribute not in config), preserves the state value.
func normalizeProtocolsOrder(ctx context.Context, req resource.ModifyPlanRequest, resp *resource.ModifyPlanResponse) {
	// Read as types.List first to safely check for null/unknown.
	// Computed+Optional attributes are unknown in plan when not in config.
	var rawPlan, rawState types.List
	resp.Diagnostics.Append(req.Plan.GetAttribute(ctx, path.Root("protocols"), &rawPlan)...)
	resp.Diagnostics.Append(req.State.GetAttribute(ctx, path.Root("protocols"), &rawState)...)
	if resp.Diagnostics.HasError() {
		return
	}

	// If plan is unknown but state is known, preserve state (UseStateForUnknown).
	if rawPlan.IsUnknown() && !rawState.IsUnknown() && !rawState.IsNull() {
		resp.Diagnostics.Append(resp.Plan.SetAttribute(ctx, path.Root("protocols"), rawState)...)
		return
	}
	if rawPlan.IsNull() || rawPlan.IsUnknown() || rawState.IsNull() || rawState.IsUnknown() {
		return
	}

	// Now safe to deserialize into typed slices.
	var planList, stateList []tfTypes.ProtocolItem
	resp.Diagnostics.Append(rawPlan.ElementsAs(ctx, &planList, false)...)
	resp.Diagnostics.Append(rawState.ElementsAs(ctx, &stateList, false)...)
	if resp.Diagnostics.HasError() {
		return
	}

	// Different count means elements were added or removed — a real change.
	if len(planList) != len(stateList) {
		return
	}

	// Build a sorted list of keys from plan and state.
	// Key = "protocol:port", e.g. "tcp:443".
	planKeys := make([]string, 0, len(planList))
	for _, p := range planList {
		if p.Protocol.IsUnknown() || p.Protocol.IsNull() || p.Port.IsUnknown() || p.Port.IsNull() {
			return // Can't compare — leave plan as-is.
		}
		planKeys = append(planKeys, fmt.Sprintf("%s:%s", p.Protocol.ValueString(), p.Port.ValueString()))
	}

	stateKeys := make([]string, 0, len(stateList))
	for _, p := range stateList {
		stateKeys = append(stateKeys, fmt.Sprintf("%s:%s", p.Protocol.ValueString(), p.Port.ValueString()))
	}

	sort.Strings(planKeys)
	sort.Strings(stateKeys)

	// If the sorted key lists are identical, plan and state have the same
	// elements in a different order. Use state to suppress the false diff.
	for i := range planKeys {
		if planKeys[i] != stateKeys[i] {
			return // Different elements — real change.
		}
	}

	resp.Diagnostics.Append(resp.Plan.SetAttribute(ctx, path.Root("protocols"), stateList)...)
}

// normalizePublishersOrder checks if plan and state have the same set of
// publishers (matched by publisher_id, or publisher_name as fallback).
// If yes, uses the state list to prevent false drift.
// If the plan is unknown (attribute not in config), preserves the state value.
func normalizePublishersOrder(ctx context.Context, req resource.ModifyPlanRequest, resp *resource.ModifyPlanResponse) {
	var rawPlan, rawState types.List
	resp.Diagnostics.Append(req.Plan.GetAttribute(ctx, path.Root("publishers"), &rawPlan)...)
	resp.Diagnostics.Append(req.State.GetAttribute(ctx, path.Root("publishers"), &rawState)...)
	if resp.Diagnostics.HasError() {
		return
	}

	if rawPlan.IsUnknown() && !rawState.IsUnknown() && !rawState.IsNull() {
		resp.Diagnostics.Append(resp.Plan.SetAttribute(ctx, path.Root("publishers"), rawState)...)
		return
	}
	if rawPlan.IsNull() || rawPlan.IsUnknown() || rawState.IsNull() || rawState.IsUnknown() {
		return
	}

	var planList, stateList []tfTypes.PublisherItem
	resp.Diagnostics.Append(rawPlan.ElementsAs(ctx, &planList, false)...)
	resp.Diagnostics.Append(rawState.ElementsAs(ctx, &stateList, false)...)
	if resp.Diagnostics.HasError() {
		return
	}

	if len(planList) != len(stateList) {
		return
	}

	// Key = publisher_id if known, otherwise publisher_name.
	planKeys := make([]string, 0, len(planList))
	for _, p := range planList {
		key := publisherKey(p)
		if key == "" {
			return // Can't compare.
		}
		planKeys = append(planKeys, key)
	}

	stateKeys := make([]string, 0, len(stateList))
	for _, p := range stateList {
		key := publisherKey(p)
		if key == "" {
			return
		}
		stateKeys = append(stateKeys, key)
	}

	sort.Strings(planKeys)
	sort.Strings(stateKeys)

	for i := range planKeys {
		if planKeys[i] != stateKeys[i] {
			return
		}
	}

	resp.Diagnostics.Append(resp.Plan.SetAttribute(ctx, path.Root("publishers"), stateList)...)
}

// publisherKey returns a string key for a publisher element.
// Uses publisher_id if known, otherwise publisher_name.
// Returns "" if neither is available.
func publisherKey(p tfTypes.PublisherItem) string {
	if !p.PublisherID.IsUnknown() && !p.PublisherID.IsNull() {
		return "id:" + p.PublisherID.ValueString()
	}
	if !p.PublisherName.IsUnknown() && !p.PublisherName.IsNull() {
		return "name:" + p.PublisherName.ValueString()
	}
	return ""
}

